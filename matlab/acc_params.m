function c = acc_params()
%ACC_PARAMS 스마트 크루즈 제어기·시나리오 가정값. 실제 현대차 제어 로직이 아니다.
c.d0    = 5;      % 정지 시 목표 간격 [m]
c.h     = 1.5;    % 목표 차간 시간 [s]: 목표 간격 = d0 + h * v
c.tau   = 0.3;    % 구동·제동 응답 지연 시정수 [s], 가정값
c.a_max = 2.0;    % 제어기 최대 가속 [m/s^2], 가정값
c.a_min = -3.5;   % 제어기 최대 감속 [m/s^2], 가정값
c.dt    = 0.01;   % 적분 간격 [s]
c.T     = 40;     % 시뮬레이션 시간 [s]
% 시나리오: 두 차 모두 100 km/h, 목표 간격에서 출발. 앞차가 5초에 -3 m/s^2로 60 km/h까지 감속 후 유지
c.v0       = 100/3.6;
c.v_lead_2 = 60/3.6;
c.a_lead   = -3;
c.t_brake  = 5;
end
